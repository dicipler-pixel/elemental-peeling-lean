#!/usr/bin/env python3
"""Inventory of the proved layer, generated from the Lean files — the paper's appendix cannot drift.

For every `results/*.lean`: the theorems, in file order, with the docstring's lead sentence (the bold
phrase if the docstring has one) and the file's own count. Writes results/light-bridge-inventory.md
and prints a per-file summary that the paper quotes.

Run: python3 scripts/paper-inventory.py
"""
import re, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
FILES = ["master-theorem", "light-bridge-theorems", "scale-theorems", "promotion-theorems",
         "merge-theorems", "generative-key", "fission-theorem", "count-formulas", "specific-heat",
         "one-equation", "digit-roles", "prime-scales"]
TITLES = {
    "master-theorem": "the master theorem, parts A–N, self-contained",
    "light-bridge-theorems": "the table: counting, the countdown, the blocks, the closures",
    "scale-theorems": "the 1·3·7·9 scale, classes and the value ladder",
    "promotion-theorems": "the 19 exchange promotions of the inventory",
    "merge-theorems": "merged segments: the total, the triple, the quadruplet, the sextuplet, the depth",
    "generative-key": "the generative key: what the digits generate",
    "fission-theorem": "the fission channel: the split, the pin, the closed pairs",
    "count-formulas": "the four prime counts and their relations (R18–R28)",
    "specific-heat": "the heat capacity in the density triangle's readings (H1–H9)",
    "one-equation": "the span law, its three readings and the acceleration form",
    "digit-roles": "the four end digits: classes, roles, the dead class 23",
    "prime-scales": "the scaled trio: energy, acceleration, mass",
}
DECL = re.compile(r"/--((?:(?!-/).)*)-/\s*(?:@\[[^\]]*\]\s*)?(?:theorem|lemma)\s+"
                  r"([A-Za-z_][A-Za-z0-9_']*)", re.S)
BOLD = re.compile(r"\*\*(.+?)\*\*", re.S)


def lead(doc: str) -> str:
    doc = doc.strip()
    m = BOLD.search(doc)
    text = m.group(1) if m else doc
    text = re.sub(r"\s+", " ", text).strip()
    text = text.replace("|", "/").replace("$", "")
    if len(text) > 120:
        cut = text[:120].rsplit(" ", 1)[0]
        text = cut + " …"
    return text


rows, summary, total = [], [], 0
for name in FILES:
    path = ROOT / "results" / (name + ".lean")
    src = path.read_text(encoding="utf-8")
    found = DECL.findall(src)
    bare = len(re.findall(r"^theorem ", src, re.M))
    if len(found) != bare:
        print("  WARNING: %s has %d theorems but %d documented" % (name, bare, len(found)))
    total += bare
    summary.append((name, bare, TITLES[name]))
    rows.append("### `%s.lean` — %d theorems\n" % (name, bare))
    rows.append("| # | theorem | what it says |")
    rows.append("|---|---|---|")
    for i, (doc, thm) in enumerate(found, 1):
        rows.append("| %d | `%s` | %s |" % (i, thm, lead(doc) if doc.strip() else "—"))
    rows.append("")

out = ["# The proved layer, in full",
       "",
       "Generated by `scripts/paper-inventory.py` from `results/*.lean`; do not edit by hand. "
       "Counts are `^theorem` lines, which is what the verifier counts.",
       "",
       "| file | theorems | subject |",
       "|---|---|---|"]
for name, n, title in summary:
    out.append("| [`%s.lean`](%s.lean) | %d | %s |" % (name, name, n, title))
out.append("| **total** | **%d** | |" % total)
out.append("")
out.extend(rows)
(ROOT / "results" / "light-bridge-inventory.md").write_text("\n".join(out) + "\n", encoding="utf-8")

for name, n, title in summary:
    print("  %-24s %3d  %s" % (name + ".lean", n, title))
print("  %-24s %3d" % ("total", total))
