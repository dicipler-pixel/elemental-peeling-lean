#!/usr/bin/env python3
# SCRIPT: VOTKP-OPENING-MAP-01
"""Regenerate `LoopWall/OpeningMap.lean` from `data/element_thresholds_20261011.json.gz`.

The opening of a noble core of N electrons in element Z is `IE(q+1)/IE(q)` with q = Z - N - 1:
the last removal above the core, then the first removal from it.  The wall side is decided in
exact integer arithmetic — `a/b > 3 + 2*sqrt2` iff `a > 3b` and `(a-3b)^2 > 8b^2` — so no
floating-point comparison decides a classification.

Two families come out of it:

* `core{He,Ne,Ar,Kr,Xe,Rn}_{outside,inside}[_n]` — one theorem per run of consecutive elements
  on the same side of the wall, cut into tens.
* `ladder{Sym}_all_inside` — every ordinary step of that element's own ladder that is inside the
  wall, for Z = 21 (Sc) to 85 (At).  Where a step is outside — the noble-core opening of Rb and
  of Cs — it is left out and the docstring says so, because it is certified in its core theorem.

Two theorems at the end are **not** derived from the archive and are emitted verbatim:
`francium_straddles`, which is an interval statement about francium's first ionization energy
(the upper end `4.0727400` is `4.0727411 - 1.1e-06`), and `frozen_prediction_Rb_Sr`, a
prediction written before the Rb and Sr ratios it names were opened.  Both are part of the
record, not of the computation.

Run from the repository root:

    python3 scripts/gen_opening_map_lean.py

It reproduces the checked-in `LoopWall/OpeningMap.lean` byte for byte
(sha256 971be82e6f1e9ff2ef5c993ff8eee9ef472865a6ef5d0a8d002bdb2119abae7f); if it stops doing
so, either the archive changed or the script did, and the difference is the thing to look at.
"""
import gzip, json, pathlib, re, sys
from fractions import Fraction

ROOT = pathlib.Path(__file__).resolve().parents[1]

CORES = [(2, "He"), (10, "Ne"), (18, "Ar"), (36, "Kr"), (54, "Xe"), (86, "Rn")]

def outside_ratio(a: str, b: str) -> bool:
    """a/b > 3 + 2*sqrt2, decided with integers: (a-3b)^2 > 8 b^2 with a > 3b."""
    A, B = Fraction(a), Fraction(b)
    d = A - 3 * B
    return d > 0 and d * d > 8 * B * B

def main():
    d = json.load(gzip.open(ROOT / "data" / "element_thresholds_20261011.json.gz"))
    ie = {}
    sym = {}
    for r in d["records"]:
        sym[r["Z"]] = r["symbol"]
        ie[r["Z"]] = {t["q"]: str(float(t["IE_eV"])) for t in r["thresholds"]}

    out = ['import LoopWall.Elements', '', 'namespace ElementalPeeling.LoopWall', '',
           '/-',
           '# SCRIPT: VOTKP-OPENING-MAP-01 (generated by gen_opening_map_lean.py)',
           'The noble-core opening map from data/element_thresholds_20261011.json.gz, using the encoded',
           'reference thresholds. For a core of N electrons and element Z the opening is IE(q+1)/IE(q) with',
           'q = Z - N - 1: the last removal above the core, then the first removal from it.',
           '-/']

    for N, label in CORES:
        items = []
        for Z in sorted(ie):
            q = Z - N - 1
            if q < 0 or q not in ie[Z] or q + 1 not in ie[Z]:
                continue
            a, b = ie[Z][q + 1], ie[Z][q]
            items.append((sym[Z], a, b, "outside" if outside_ratio(a, b) else "inside"))
        # maximal runs by side
        runs = []
        for it in items:
            if runs and runs[-1][0] == it[3]:
                runs[-1][1].append(it)
            else:
                runs.append([it[3], [it]])
        seen = {"inside": 0, "outside": 0}
        for side, run in runs:
            for i in range(0, len(run), 10):
                chunk = run[i:i + 10]
                seen[side] += 1
                name = (f"core{label}_{side}" if side == "outside" and seen[side] == 1
                        else f"core{label}_{side}_{seen[side]}")
                names = ", ".join(c[0] for c in chunk)
                out.append(f"/-- {label}-like core: {side} the wall for {names}. -/")
                out.append(f"theorem {name} :")
                body = [f"    {side} ({c[1]} / {c[2]} : Rat)" for c in chunk]
                out.append(" ∧\n".join(body) + " := by")
                holes = ", ".join(["?_"] * len(chunk))
                out.append(f"  unfold {side}; grind" if len(chunk) == 1
                           else f"  unfold {side}; refine ⟨{holes}⟩ <;> grind")
                out.append("")

    for Z in range(21, 86):
        if not ie.get(Z):
            continue
        steps = []
        skipped = []
        for q in range(0, max(ie[Z])):
            if q + 1 in ie[Z]:
                a, b = ie[Z][q + 1], ie[Z][q]
                if outside_ratio(a, b):
                    skipped.append(q)
                else:
                    steps.append((a, b))
        if not steps:
            continue
        note = ""
        if skipped:
            note = (", except the step from removal %d to removal %d (the noble-core opening, "
                    "certified in its core theorem)" % (skipped[0] + 1, skipped[0] + 2))
        out.append(f"/-- Every ordinary step of the {sym[Z]} ladder ({len(steps)} steps) is inside the wall{note}. -/")
        out.append(f"theorem ladder_{sym[Z]}_all_inside :")
        out.append(" ∧\n".join(f"    inside ({a} / {b} : Rat)" for a, b in steps) + " := by")
        out.append(f"  unfold inside; refine ⟨{', '.join(['?_'] * len(steps))}⟩ <;> grind")
        out.append("")

    out.append("/-- Francium: the encoded central opening ratio is inside, but the input interval straddles the")
    out.append("wall: IE1 = 4.0727411(1.1e-06) eV, IE2 = 22.4(1.9) eV (S). -/")
    out.append("theorem francium_straddles :")
    out.append("    inside (22.4 / 4.0727411 : Rat) \u2227")
    out.append("    inside (20.5 / 4.0727422 : Rat) \u2227")
    out.append("    outside (24.3 / 4.0727400 : Rat) := by")
    out.append("  unfold inside outside; refine \u27e8?_, ?_, ?_\u27e9 <;> grind")
    out.append("")
    out.append("")
    out.append("/-- The frozen prediction (written before the Rb and Sr ratios were opened): the Kr-core opening")
    out.append("is outside for rubidium and inside for strontium. Both hold. -/")
    out.append("theorem frozen_prediction_Rb_Sr :")
    out.append("    outside (27.28954 / 4.1771281 : Rat) \u2227 inside (42.88353 / 11.0302765 : Rat) := by")
    out.append("  unfold outside inside; constructor <;> grind")
    out.append("")
    out.append("end ElementalPeeling.LoopWall")
    text = "\n".join(out) + "\n"
    target = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "LoopWall" / "OpeningMap.lean"
    target.write_text(text)
    ratios = sum(len(re.findall(r"\b(?:inside|outside) \(", l)) for l in out)
    theorems = sum(1 for l in out if l.startswith("theorem "))
    shown = target.relative_to(ROOT) if target.is_absolute() and ROOT in target.parents else target
    print(f"wrote {shown}: {ratios} ratios in {theorems} theorems")

main()
